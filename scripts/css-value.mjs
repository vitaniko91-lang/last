// Сериализация значений токенов в CSS. Отдельный модуль, потому что
// build-tokens.mjs при импорте читает и пишет файлы, а правила здесь чистые.

/** Валидный CSS-идентификатор: не начинается с цифры, дефис только ведущий. */
const IDENT = /^-?[A-Za-z_\u00a0-\uffff][A-Za-z0-9_\-\u00a0-\uffff]*$/

/**
 * Имя семейства без кавычек — это последовательность идентификаторов. Любая
 * часть, которая идентификатором не является («4» в «Source Serif 4»), делает
 * всё объявление невалидным: браузер отбрасывает его целиком и молча оставляет
 * унаследованный шрифт. Ошибка не видна ни в консоли, ни в данных — только в
 * getComputedStyle. Поэтому такие имена берём в кавычки.
 *
 * Родовые ключевые слова (serif, sans-serif, system-ui) кавычить НЕЛЬЗЯ:
 * в кавычках они перестают быть ключевыми словами и ищутся как имя семейства.
 * Отдельного списка им не нужно — они и так проходят проверку на идентификатор.
 */
export function cssFontFamily(names) {
  return names
    .map((name) => {
      const raw = String(name).trim()
      const safe = raw.split(/\s+/).every((part) => IDENT.test(part))
      return safe ? raw : `"${raw.replace(/(["\\])/g, '\\$1')}"`
    })
    .join(', ')
}
